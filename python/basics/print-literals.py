print("2") # this is a string literal, not a number
print(2) # this is a number literal, not a string

print(0o123) # This is  is an octal number with a (decimal) value equal to 83.

print(0x123) # This is a hexadecimal number with a (decimal) value equal to 291.

print(0.0000000000000000000001) # This is a floating point number with a (decimal) value equal to 1e-22.

print("I like \"Steak\"") # This is a string literal with an escaped double quote character.

print('I like "Steak"') # This is a string literal with a double quote character.

# If you open a string with a quote, you have to close it with a quote.

# If you start a string with an apostrophe, you have to end it with an apostrophe.